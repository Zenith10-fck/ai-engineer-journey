# Minggu 1 - Task 08 - Bagian 1: variabel dan type hint

nama: str = "ahmad"
umur: int = 21
tinggi: float = 1.7
aktif: bool = True
kota: str = "Cirebon"
semester: int = 7

print(nama, umur, tinggi, aktif, kota, semester)

# type() menunjukkan jenis nilai sebenarnya
print(type("21"))  # <class 'str'>  (ada tanda kutip = teks)
print(type(21))  # <class 'int'>  (tanpa kutip = angka bulat)
print(type(semester))  # <class 'int'>
